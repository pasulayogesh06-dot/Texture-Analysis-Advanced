from io import BytesIO
from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet

def create_pdf_report(filename, image_info, glcm, metrics=None):
    buffer=BytesIO()
    doc=SimpleDocTemplate(buffer,pagesize=A4,rightMargin=42,leftMargin=42,topMargin=42,bottomMargin=42)
    styles=getSampleStyleSheet()
    story=[Paragraph("Digital Image Processing — Analysis Report",styles["Title"]),
           Spacer(1,14),Paragraph("Image information",styles["Heading2"])]
    rows=[["Property","Value"]]+[[str(k),str(v)] for k,v in image_info.items()]
    t=Table(rows,hAlign="LEFT"); t.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,0),colors.HexColor("#26364a")),
        ("TEXTCOLOR",(0,0),(-1,0),colors.white),("GRID",(0,0),(-1,-1),0.4,colors.grey),("PADDING",(0,0),(-1,-1),7)]))
    story += [t,Spacer(1,14),Paragraph("GLCM texture features",styles["Heading2"])]
    rows=[["Feature","Value"]]+[[k,f"{v:.6g}"] for k,v in glcm.items()]
    t=Table(rows,hAlign="LEFT"); t.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,0),colors.HexColor("#26364a")),
        ("TEXTCOLOR",(0,0),(-1,0),colors.white),("GRID",(0,0),(-1,-1),0.4,colors.grey),("PADDING",(0,0),(-1,-1),7)]))
    story += [t]
    if metrics:
        story += [Spacer(1,14),Paragraph("Image quality metrics",styles["Heading2"])]
        rows=[["Metric","Value"]]+[[k,str(v)] for k,v in metrics.items()]
        t=Table(rows,hAlign="LEFT"); t.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,0),colors.HexColor("#26364a")),
            ("TEXTCOLOR",(0,0),(-1,0),colors.white),("GRID",(0,0),(-1,-1),0.4,colors.grey),("PADDING",(0,0),(-1,-1),7)]))
        story += [t]
    story.append(Spacer(1,18))
    story.append(Paragraph("Generated by Texture Analysis Studio. Metrics are computed from the uploaded image and selected processing output.",styles["Italic"]))
    doc.build(story)
    return buffer.getvalue()
